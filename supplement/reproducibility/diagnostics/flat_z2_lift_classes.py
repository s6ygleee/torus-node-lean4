"""Flat Z2 classes of the lifted cuboctahedral complex and their symmetry orbits.

The cuboctahedral graph is the line graph of the cube.  Its four-cycles carry the deck
voltages D_a = C_i - s_a C_j (pairs of opposite squares; mask = relative signs s_a), which
define the Z^3 cover.  For a given mask the script computes
  * the cycle-voltage lattice Lam (image of H1(graph; Z) in Z^3); the flat Z2 classes of the
    lifted complex are Hom(Lam, Z2);
  * the graph automorphisms that lift to the cover and their integer action on Lam;
  * the classes fixed by all lifted automorphisms and by the orientation-preserving ones.
Output: JSON on stdout.  Exact integer arithmetic except the integrality checks of the
lifted action, which compare floating-point solutions with their rounded values.
"""
import itertools, json, sys
import numpy as np

cubeAdj = {0:[1,3,4],1:[0,2,7],2:[1,3,6],3:[0,2,5],4:[0,5,7],5:[3,4,6],6:[2,5,7],7:[1,4,6]}
cubeEdges = sorted({tuple(sorted((u, v))) for u in cubeAdj for v in cubeAdj[u]})
nodes = sorted(tuple(sorted(e)) for e in cubeEdges)
idx = {n: i for i, n in enumerate(nodes)}
V = len(nodes)
adj = [set() for _ in range(V)]
for i in range(V):
    for j in range(i + 1, V):
        if set(nodes[i]) & set(nodes[j]):
            adj[i].add(j); adj[j].add(i)
edges = sorted((i, j) for i in range(V) for j in adj[i] if i < j)
E = len(edges)
eidx = {e: k for k, e in enumerate(edges)}
def edgeOf(a, b):
    return (eidx[(a, b)], 1) if a < b else (eidx[(b, a)], -1)

squares = []
for comb in itertools.combinations(range(V), 4):
    deg = [len([y for y in adj[x] if y in comb]) for x in comb]
    if sum(deg) // 2 != 4 or any(d != 2 for d in deg):
        continue
    start = min(comb)
    nbr = sorted(y for y in adj[start] if y in comb)[0]
    cyc = [start, nbr]; prev, cur = start, nbr
    while len(cyc) < 4:
        cand = sorted(x for x in adj[cur] if x in comb and x != prev and x not in cyc)
        if not cand: break
        cyc.append(cand[0]); prev, cur = cur, cand[0]
    if len(cyc) != 4: continue
    reps = []
    for seq in (cyc, cyc[::-1]):
        for k in range(4):
            reps.append(tuple(seq[k:] + seq[:k]))
    c = min(reps)
    if c not in squares: squares.append(c)
squares.sort()

def cycleVec(cyc):
    v = np.zeros(E, dtype=int)
    for i in range(len(cyc)):
        e, s = edgeOf(cyc[i], cyc[(i + 1) % len(cyc)]); v[e] += s
    return v

C = [cycleVec(s) for s in squares]
pairs = [(i, j) for i in range(len(squares)) for j in range(i + 1, len(squares)) if not set(squares[i]) & set(squares[j])]
tris = [t for t in itertools.combinations(range(V), 3) if t[1] in adj[t[0]] and t[2] in adj[t[1]] and t[2] in adj[t[0]]]
cycles = [list(t) for t in tris] + [list(s) for s in squares]


def int_basis(rows):
    """Row-style integer echelon basis of the lattice spanned by rows (Euclid on columns)."""
    M = [list(map(int, r)) for r in rows]
    basis = []
    ncol = len(M[0])
    r0 = 0
    for c in range(ncol):
        piv = [i for i in range(r0, len(M)) if M[i][c] != 0]
        while len(piv) > 1:
            piv.sort(key=lambda i: abs(M[i][c]))
            p = piv[0]
            for i in piv[1:]:
                q = M[i][c] // M[p][c]
                M[i] = [a - q * b for a, b in zip(M[i], M[p])]
            piv = [i for i in range(r0, len(M)) if M[i][c] != 0]
        if piv:
            p = piv[0]
            M[r0], M[p] = M[p], M[r0]
            r0 += 1
    return [r for r in M[:r0]]

def analyse(mask):
    sgn = [-1 if (mask >> a) & 1 else 1 for a in range(3)]
    D = np.array([C[i] - sgn[a] * C[j] for a, (i, j) in enumerate(pairs)])  # 3 x E
    Vz = lambda z: D @ cycleVec(z)
    base = np.array([Vz(z) for z in cycles])  # cycles span H1(graph)
    # lattice Lam generated by rows of base
    # integer basis of Lam (3 rows)
    Bl = np.array(int_basis(base.tolist()))
    # automorphisms of the cube -> of cuboctahedron
    auts = [p for p in itertools.permutations(range(8)) if all(p[v] in cubeAdj[p[u]] for u, v in cubeEdges)]
    Ls = []
    for p in auts:
        nm = [idx[tuple(sorted((p[u], p[v])))] for (u, v) in nodes]
        img = np.array([Vz([nm[v] for v in z]) for z in cycles])
        # solve L base^T = img^T  (least squares, then check integrality)
        L, *_ = np.linalg.lstsq(base, img, rcond=None)
        L = L.T
        if np.allclose(L, np.round(L), atol=1e-9) and np.allclose(base @ L.T, img, atol=1e-9):
            Ls.append(np.round(L).astype(int))
    # action on Lam in its own basis Bl: g(b_i) = sum_j A_ij b_j
    Binv = np.linalg.pinv(Bl.astype(float))
    acts = []
    for L in Ls:
        A = (Bl @ L.T) @ Binv
        assert np.allclose(A, np.round(A), atol=1e-8)
        acts.append(np.round(A).astype(int))
    # Z2 classes: phi in F2^3 (phi(b_i)); action phi -> phi o g^{-1}; fixed iff phi(g b_i)=phi(b_i)
    classes = list(itertools.product([0, 1], repeat=len(Bl)))
    def fixed(group):
        out = []
        for phi in classes:
            ph = np.array(phi)
            if all(np.array_equal((A @ ph) % 2, ph % 2) for A in group):
                out.append(phi)
        return out
    det = [int(round(np.linalg.det(L))) for L in Ls]
    rot = [A for A, d in zip(acts, det) if d == 1]
    # orbits of all classes under full lifted group
    orbits, seen = [], set()
    for phi in classes:
        if phi in seen: continue
        orb = {tuple((A @ np.array(phi)) % 2) for A in acts}
        seen |= orb; orbits.append(sorted(orb))
    return {'mask': mask, 'lifted_automorphisms': len(Ls), 'lattice_index_in_Z3': int(round(abs(np.linalg.det(Bl)))) if len(Bl)==3 else None,
            'lattice_basis': Bl.tolist(), 'num_Z2_classes': len(classes),
            'fixed_by_all_lifted': fixed(acts), 'fixed_by_det+1_lifted': fixed(rot),
            'orbit_sizes': [len(o) for o in orbits], 'orbits': orbits}

if __name__ == '__main__':
    res = [analyse(m) for m in (4, 0)]
    print(json.dumps(res, indent=1, default=int))
